-- Expense Voucher Management System: MySQL 8.0.16+ schema
-- Run:  mysql -u root -p < schema_mysql.sql

CREATE DATABASE IF NOT EXISTS expense_voucher;
USE expense_voucher;

-- 1) Users table: one table for all three roles, the role column decides access
CREATE TABLE users (
  id            INT AUTO_INCREMENT PRIMARY KEY,
  name          VARCHAR(100) NOT NULL,
  email         VARCHAR(150) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role          ENUM('employee', 'director', 'accounts') NOT NULL,
  employee_code VARCHAR(30),                       -- optional Employee ID
  created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- 2) Vouchers table: the main object of the whole project
CREATE TABLE vouchers (
  id                       INT AUTO_INCREMENT PRIMARY KEY,

  -- generated by the backend right after INSERT, e.g. VCH-2026-0001
  -- (MySQL cannot build it from the auto-increment id inside the table itself)
  voucher_number           VARCHAR(30) UNIQUE,

  -- who created it (relationship: one user has many vouchers)
  employee_id              INT NOT NULL,

  -- basic information
  voucher_date             DATE NOT NULL DEFAULT (CURRENT_DATE),
  expense_date             DATE NOT NULL,
  department               VARCHAR(100) NOT NULL,
  expense_title            VARCHAR(200) NOT NULL,
  expense_category         VARCHAR(50),
  expense_description      TEXT,
  amount                   DECIMAL(12,2) NOT NULL,

  -- employee signature (we store the file path, not the image itself)
  employee_signature_path  VARCHAR(255),

  -- approval information
  -- Assumption: "Submitted" and "Pending Approval" are merged into pending_approval
  status                   ENUM('draft', 'pending_approval', 'approved', 'rejected')
                           NOT NULL DEFAULT 'draft',
  director_id              INT NULL,
  director_signature_path  VARCHAR(255),
  approval_date            DATETIME NULL,
  rejection_reason         TEXT,

  -- audit information (MySQL updates updated_at by itself on every change)
  created_at               TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at               TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                           ON UPDATE CURRENT_TIMESTAMP,

  -- relationships
  CONSTRAINT fk_voucher_employee FOREIGN KEY (employee_id) REFERENCES users(id),
  CONSTRAINT fk_voucher_director FOREIGN KEY (director_id) REFERENCES users(id),

  -- business rules enforced by the database itself
  CONSTRAINT chk_amount_positive
    CHECK (amount > 0),
  CONSTRAINT chk_signature_needed_after_submit
    CHECK (status = 'draft' OR employee_signature_path IS NOT NULL),
  CONSTRAINT chk_director_signature_for_approval
    CHECK (status <> 'approved' OR director_signature_path IS NOT NULL),
  CONSTRAINT chk_rejection_reason_needed
    CHECK (status <> 'rejected' OR rejection_reason IS NOT NULL),

  INDEX idx_vouchers_status (status)
) ENGINE=InnoDB;